// Javascript numbers can be of two types: integers and floating-point numbers. Here are some examples of how to work with numbers in JavaScript:

// Integer
let intNum = 42;
console.log(intNum); // Output: 42

// Floating-point number
let floatNum = 3.14;
console.log(floatNum); // Output: 3.14

// Basic arithmetic operations
let a = 10;
let b = 3;  
console.log(a + b); // Addition: Output: 13
console.log(a - b); // Subtraction: Output: 7
console.log(a * b); // Multiplication: Output: 30
console.log(a / b); // Division: Output: 3.3333333333333335
console.log(a % b); // Modulus: Output: 1   
// Increment and Decrement
let count = 5;
count++;
console.log(count); // Output: 6
count--;
console.log(count); // Output: 5
// Math object for advanced mathematical operations
console.log(Math.sqrt(16));
// Output: 4
console.log(Math.pow(2, 3));
// Output: 8

console.log(Math.random());
// Output: A random number between 0 and 1
console.log(Math.round(4.7));
// Output: 5
console.log(Math.floor(4.7));
// Output: 4
console.log(Math.ceil(4.2));
// Output: 5
// Summary:
// - JavaScript supports both integers and floating-point numbers.
// - You can perform basic arithmetic operations using standard operators (+, -, *, /, %).
// - The Math object provides various methods for advanced mathematical operations.

